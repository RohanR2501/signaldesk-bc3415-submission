"""Export canonical schema definitions and the implemented API's frontend type.

This utility describes interfaces; it does not fabricate data or expose future routes.
"""

import argparse
import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from signaldesk.contracts import (
    AnalyzeRequest,
    AnalyzeResponse,
    ComplaintPrediction,
    CustomerReview,
    ErrorResponse,
    ExecutiveSummary,
    HealthResponse,
    HumanReviewDecision,
    InvestigationDetail,
    InvestigationSignal,
    ModelEvaluationResult,
    Page,
    ProductDetail,
    ProductIncidentAlert,
    ProductSummary,
    ProductTimeline,
    ReviewEvidenceResponse,
    SentimentPrediction,
)

ROOT = Path(__file__).resolve().parents[1]


def typescript_type(schema: dict[str, Any]) -> str:
    """Translate our canonical JSON Schema subset; fail on unsupported shapes."""
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(typescript_type(part) for part in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(typescript_type(part) for part in schema["prefixItems"]) + "]"
        return f"Array<{typescript_type(schema['items'])}>"
    if kind == "object":
        if "properties" in schema:
            # Responses serialize defaults. Requiring them prevents UI code from
            # silently treating omitted metrics/states as real zero values.
            return (
                "{\n"
                + "\n".join(
                    f"  {json.dumps(name)}: {typescript_type(value)};"
                    for name, value in schema["properties"].items()
                )
                + "\n}"
            )
        key = typescript_type(schema["propertyNames"]) if "propertyNames" in schema else "string"
        value = schema.get("additionalProperties", {})
        return f"Record<{key}, {typescript_type(value) if isinstance(value, dict) else 'unknown'}>"
    if kind in {"integer", "number"}:
        return "number"
    if kind in {"string", "boolean", "null"}:
        return str(kind)
    if not schema:
        return "unknown"
    raise ValueError("Extend the TypeScript exporter for an unsupported schema shape")


def exports() -> dict[Path, str]:
    models: list[type[BaseModel]] = [
        HealthResponse,
        ErrorResponse,
        CustomerReview,
        SentimentPrediction,
        ComplaintPrediction,
        ProductIncidentAlert,
        ModelEvaluationResult,
        HumanReviewDecision,
        AnalyzeRequest,
        AnalyzeResponse,
        ExecutiveSummary,
        ProductDetail,
        ProductTimeline,
        Page[ProductSummary],
        Page[InvestigationSignal],
        InvestigationDetail,
        ReviewEvidenceResponse,
    ]
    _, schema = models_json_schema(
        [(model, "validation") for model in models],
        title="SignalDesk canonical business 1.1 and legacy experiment 1.0 contracts",
    )
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"

    typescript = (
        "// Generated by scripts/export_contracts.py. Do not edit manually.\n"
        "// Serialized response types include Pydantic defaults. Legacy types are not served.\n"
        + "\n\n".join(
            f"export type {name} = {typescript_type(definition)};"
            for name, definition in sorted(schema["$defs"].items())
        )
        + "\n"
    )
    return {
        ROOT / "docs/contracts/schema-v1.json": json.dumps(schema, indent=2, sort_keys=True) + "\n",
        ROOT / "frontend/src/api/contracts.generated.ts": typescript,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if committed exports are stale")
    args = parser.parse_args()
    stale = []
    for path, content in exports().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("Stale contract exports: " + ", ".join(stale))
        return 1
    print("Contract exports are current." if args.check else "Contract exports written.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
